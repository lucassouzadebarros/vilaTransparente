-- Paying a bill by Pix from the condominium's Asaas account. Each request is kept with what Asaas answers (its id, the
-- status, the receipt), so the bill is settled when Asaas confirms it and Asaas can check, before sending the money,
-- that the transfer really came from here.
create table pix_transfers (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  payable_id bigint not null references payables(id),
  amount numeric(12,2) not null,
  pix_key varchar(140) not null,
  pix_key_type varchar(10) not null,
  gateway_transfer_id varchar(80),
  status varchar(20) not null,
  fail_reason text,
  receipt_url text,
  end_to_end_id varchar(80),
  fee numeric(12,2),
  requested_by varchar(160) not null,
  requested_at timestamp not null default now(),
  confirmed_at timestamp,
  updated_at timestamp not null default now()
);

create index ix_pix_transfers_payable on pix_transfers(condominium_id, payable_id);
create index ix_pix_transfers_status on pix_transfers(condominium_id, status);
create unique index ux_pix_transfers_gateway on pix_transfers(gateway_transfer_id);

-- Where Asaas asks whether a withdrawal may go out (Integrações > Mecanismos de segurança). Not filtered by condominium:
-- the request finds it by its route before anyone knows whose it is. The token is sealed so the administration can see
-- it again to type it in Asaas.
create table pix_validations (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null unique references condominiums(id),
  route_key varchar(64) not null unique,
  token_sealed text not null,
  created_by varchar(160),
  created_at timestamp not null default now(),
  last_check_at timestamp
);

-- Most that may leave by Pix in a day. Empty turns paying by Pix off.
alter table settings add column pix_daily_limit numeric(12,2) default 3000;
