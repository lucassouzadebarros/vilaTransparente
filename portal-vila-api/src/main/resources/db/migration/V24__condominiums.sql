-- Several condominiums in one app. Everything that exists today is the first one: the Vila.
-- The column starts with the Vila as its default, so the code that does not know about condominiums yet
-- (and every row already stored) keeps working exactly as before. The next phase stamps the condominium
-- explicitly on every insert, filters every read by it, and drops these defaults.
create table condominiums (
  id bigint generated by default as identity primary key,
  name varchar(140) not null,
  slug varchar(60) not null,
  status varchar(20) not null default 'ACTIVE',
  created_at timestamp not null default now()
);

create unique index uq_condominiums_slug on condominiums(slug);

-- First row of a new table: its id is 1, which is what the column defaults below point at.
insert into condominiums (name, slug, status)
select coalesce(max(village_name), 'Vila'), 'vila', 'ACTIVE' from settings;

