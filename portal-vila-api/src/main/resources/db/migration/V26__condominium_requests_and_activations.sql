-- Someone asks for their condominium to use the app (a public form). Nothing is created until the platform approves it.
-- Not inside any condominium: it comes before one exists.
create table condominium_requests (
  id bigint generated by default as identity primary key,
  condominium_name varchar(140) not null,
  city varchar(80) not null,
  state varchar(2) not null,
  units integer not null,
  contact_name varchar(120) not null,
  contact_email varchar(160) not null,
  contact_phone varchar(30),
  has_asaas varchar(10) not null default 'NAO_SEI',
  message varchar(1000),
  status varchar(20) not null default 'PENDING',
  created_at timestamp not null default now(),
  decided_at timestamp,
  decided_by varchar(160),
  decision_note varchar(500),
  condominium_id bigint references condominiums(id)
);

create index idx_condominium_requests_status on condominium_requests(status, created_at);

-- The first access of the person who runs a new condominium: a single-use code (only its hash is kept) with which they
-- choose their own password. No password is ever sent. Looked up by the code, before anyone is signed in.
create table account_activations (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  user_id bigint not null references app_users(id) on delete cascade,
  code_hash varchar(64) not null,
  expires_at timestamp not null,
  used_at timestamp,
  revoked_at timestamp,
  created_by varchar(160),
  created_at timestamp not null default now()
);

create unique index uq_account_activations_code_hash on account_activations(code_hash);
create index idx_account_activations_condominium on account_activations(condominium_id);
