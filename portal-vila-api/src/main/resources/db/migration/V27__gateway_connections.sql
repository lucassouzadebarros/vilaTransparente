-- A condominium's own Asaas account, connected from the web panel. The API key is stored sealed (AES-GCM, with a key the
-- server keeps outside the database); only its last characters are kept in the clear, to show which key it is.
-- The Vila does not use this table: its key stays in the server's settings, as before.
create table gateway_connections (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  provider varchar(20) not null default 'ASAAS',
  api_key_sealed text not null,
  api_key_hint varchar(12) not null,
  account_name varchar(160),
  webhook_id varchar(80),
  -- The notices from Asaas arrive at /api/webhooks/asaas/c/{route_key} with a token only Asaas and the server know.
  route_key varchar(64) not null,
  webhook_token_hash varchar(64) not null,
  connected_by varchar(160),
  connected_at timestamp not null default now(),
  last_event_at timestamp
);

create unique index uq_gateway_connections_condominium on gateway_connections(condominium_id);
create unique index uq_gateway_connections_route on gateway_connections(route_key);
