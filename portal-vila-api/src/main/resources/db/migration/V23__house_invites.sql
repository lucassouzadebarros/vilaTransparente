create table house_invites (
  id bigint generated by default as identity primary key,
  house_id bigint not null references houses(id),
  code_hash varchar(64) not null,
  created_by varchar(255),
  created_at timestamp not null default now(),
  expires_at timestamp not null,
  used_at timestamp,
  used_by_resident_id bigint,
  revoked_at timestamp
);

create unique index uq_house_invites_code_hash on house_invites(code_hash);
create index idx_house_invites_house_id on house_invites(house_id);
