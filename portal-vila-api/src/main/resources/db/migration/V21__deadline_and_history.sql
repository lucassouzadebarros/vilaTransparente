-- Historico e comentarios do relato (sem chave estrangeira, como as outras ligacoes, para nao travar a limpeza de dados).
create table problem_report_events (
  id bigint generated by default as identity primary key,
  report_id bigint not null,
  kind varchar(20) not null,
  author varchar(80),
  message text not null,
  created_at timestamp not null default now()
);

create index idx_problem_report_events_report on problem_report_events(report_id);
