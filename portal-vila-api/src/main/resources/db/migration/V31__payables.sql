-- Bills to pay: who the condominium pays (suppliers, with their Pix key for later), each bill with its due date, the
-- approval when it is large, and the payment that turns it into an expense with its receipt. Who may pay besides the
-- administration (the síndico) and above which value a second person must approve are set per condominium.
create table suppliers (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  name varchar(160) not null,
  document varchar(20),
  pix_key varchar(140),
  pix_key_type varchar(10),
  phone varchar(30),
  email varchar(160),
  notes text,
  active boolean not null default true,
  created_at timestamp not null default now()
);

create table payables (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  supplier_id bigint references suppliers(id),
  description varchar(200) not null,
  category varchar(60),
  amount numeric(12,2) not null,
  due_date date not null,
  status varchar(20) not null,
  installment integer,
  installments integer,
  group_key varchar(40),
  recurrence varchar(10),
  budget_id bigint,
  service_order_id bigint,
  document_id bigint,
  exception_reason text,
  notes text,
  created_by varchar(160),
  created_at timestamp not null default now(),
  approved_by varchar(160),
  approved_at timestamp,
  paid_by varchar(160),
  paid_at date,
  payment_method varchar(20),
  receipt_document_id bigint,
  expense_id bigint,
  cancelled_by varchar(160),
  cancelled_at timestamp,
  cancel_reason text,
  updated_at timestamp not null default now()
);

create index ix_payables_due on payables(condominium_id, status, due_date);

alter table settings add column sindico_can_pay boolean not null default false;
alter table settings add column approval_above numeric(12,2);
