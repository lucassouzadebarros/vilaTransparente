-- Dividing the month among the units by their ideal fraction (or area, or any weight the convention uses), instead of the
-- same value for every unit; and charging water and gas by the meter. Every condominium starts as today: same value.
alter table houses add column ideal_fraction numeric(14,6);

alter table settings add column charge_mode varchar(20) not null default 'FIXED';
alter table settings add column monthly_total numeric(12,2);
alter table settings add column water_price numeric(10,4);
alter table settings add column gas_price numeric(10,4);

-- One reading per unit, meter and month: the meter at the end of the month, the one before, what was used, and the charge
-- it became (so it is never charged twice).
create table meter_readings (
  id bigint generated by default as identity primary key,
  condominium_id bigint not null references condominiums(id),
  house_id bigint not null references houses(id),
  kind varchar(10) not null,
  reference_month varchar(7) not null,
  previous_reading numeric(12,3),
  reading numeric(12,3) not null,
  consumption numeric(12,3),
  unit_price numeric(10,4),
  amount numeric(12,2),
  contribution_id bigint,
  recorded_by varchar(160),
  created_at timestamp not null default now(),
  updated_at timestamp not null default now()
);

create unique index uq_meter_readings on meter_readings(condominium_id, house_id, kind, reference_month);
